static void set_vga_mode_regs(uint8_t misc, const uint8_t *seq,
                              const uint8_t *crtc, const uint8_t *gc,
                              const uint8_t *ac) {
    /* Misc output */
    outb(0x3C2, misc);

    /* Sequencer */
    for (uint8_t i = 0; i < 5; i++) {
        outb(0x3C4, i);
        outb(0x3C5, seq[i]);
    }

    /* Unlock CRTC registers 0-7 */
    outb(0x3D4, 0x03);
    outb(0x3D5, inb(0x3D5) | 0x80);
    outb(0x3D4, 0x11);
    outb(0x3D5, inb(0x3D5) & ~0x80);

    /* CRTC */
    for (uint8_t i = 0; i < 25; i++) {
        outb(0x3D4, i);
        outb(0x3D5, crtc[i]);
    }

    /* Graphics Controller */
    for (uint8_t i = 0; i < 9; i++) {
        outb(0x3CE, i);
        outb(0x3CF, gc[i]);
    }

    /* Attribute Controller */
    for (uint8_t i = 0; i < 21; i++) {
        inb(0x3DA); /* reset flip-flop */
        outb(0x3C0, i);
        outb(0x3C0, ac[i]);
    }

    /* Enable video output */
    inb(0x3DA);
    outb(0x3C0, 0x20);
}

